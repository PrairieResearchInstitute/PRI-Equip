-- 0003: role grants for NetID identity (owner, 2026-10-12; D-015).
-- On Radiant the university's authenticating proxy says who a person is (NetID)
-- and, when configured, which campus groups they belong to. This table says what
-- that NetID or group may do here: member (use the laboratory screens; with a
-- lab_id, belong to that laboratory), admin (the administrative panel) or
-- code_editor (the panel and the Studio). Rows are never deleted: a revoked
-- grant keeps revoked_at and revoked_by so an auditor can see who held what.
-- admin_users and login_attempts stay for the password mode on this computer.
CREATE TABLE "role_grants" (
    "grant_id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "principal_kind" text NOT NULL,
    "principal" text NOT NULL,
    "role" text NOT NULL,
    "lab_id" integer REFERENCES "labs" ("lab_id"),
    "note" text NOT NULL DEFAULT '',
    "granted_by" text NOT NULL DEFAULT '',
    "granted_at" text NOT NULL,
    "revoked_by" text,
    "revoked_at" text,
    CHECK ("principal_kind" IN ('netid', 'group')),
    CHECK ("role" IN ('member', 'admin', 'code_editor')),
    CHECK ("principal" = lower("principal") AND "principal" <> '')
);

CREATE INDEX "idx_role_grants_principal" ON "role_grants" ("principal_kind", "principal");
